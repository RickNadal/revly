function regionDefault(): SupportedLang {
  const loc = Localization.getLocales?.()?.[0];
  const lang = (loc as any)?.languageCode ? String((loc as any).languageCode).toLowerCase() : "";
  if (lang === "en") return "en";
  return "nl";
}

export async function initI18n(): Promise<void> {
  let saved: string | null = null;

  try {
    saved = await AsyncStorage.getItem(STORAGE_KEY);
  } catch {}

  const initial = (saved && SUPPORTED_LANGS.includes(saved as SupportedLang) ? saved : regionDefault()) as SupportedLang;

  if (!i18n.isInitialized) {
    await i18n.use(initReactI18next).init(
      {
        resources: resources as any,
        lng: initial,
        fallbackLng: "nl",
        interpolation: { escapeValue: false },
        compatibilityJSON: "v4",
      } as any
    );
  } else {
    await i18n.changeLanguage(initial);
  }
}

export async function setAppLanguage(lang: SupportedLang): Promise<void> {
  await i18n.changeLanguage(lang);
  try {
    await AsyncStorage.setItem(STORAGE_KEY, lang);
  } catch {}
}

export async function clearAppLanguageOverride(): Promise<void> {
  try {
    await AsyncStorage.removeItem(STORAGE_KEY);
  } catch {}
  await i18n.changeLanguage(regionDefault());
}

export default i18n;